function BBF.ShiftRegionY(region, shift)
    if not region or region:GetNumPoints() == 0 then return end
    shift = shift or 0
    if not region.bbfShiftHooked then
        region.bbfShiftHooked = true
        hooksecurefunc(region, "SetPoint", function(self)
            if self.bbfShifting or not self.bbfShiftY then return end
            local wanted = self.bbfShiftY
            self.bbfShiftY = nil
            BBF.ShiftRegionY(self, wanted)
        end)
    end
    local old = region.bbfShiftY or 0
    if old == shift then return end
    local point, rel, relPoint, x, y = region:GetPoint(1)
    region.bbfShifting = true
    region:SetPoint(point, rel, relPoint, x, y - old + shift)
    region.bbfShifting = nil
    region.bbfShiftY = shift ~= 0 and shift or nil
end

local function ApplyCoords(tex)
    local info = ART[tex.bbfRetailArt]
    local left, right = info[4], info[5]
    local top, bottom = info[6], info[7]
    if tex.bbfRetailWhole then
        left, right, top, bottom = 0, 1, 0, 1
    end
    if tex.bbfRetailFlip then
        left, right = right, left
    end
    tex.bbfRetailBusy = true
    tex:SetTexCoord(left, right, top, bottom)
    tex.bbfRetailBusy = nil
end

function BBF.SetRetailArt(tex, key, flip, width, height)
    local info = tex and ART[key]
    if not info then return false end
    local prepatch = PREPATCH_BASE[key] and BBF.RetailPrepatchOn() or nil
    local fileKey = prepatch and prepatchSheetFile[key] or key
    local file = prepatch and PREPATCH_TEX .. fileKey .. ".png"
    if noShadowSheet[key] and BBF.RetailNoShadowOn() then
        file = (prepatch and PREPATCH_TEX or RETAIL_TEX) .. NO_SHADOW .. fileKey .. ".png"
    end
    tex.bbfRetailBusy = true
    tex:SetTexture(file or info[1])
    tex.bbfRetailBusy = nil
    tex.bbfRetailPrepatch = prepatch
    tex.bbfRetailWhole = file and true or nil
    tex.bbfRetailArt = key
    tex.bbfRetailFile = nil
    tex.bbfRetailFlip = flip and true or nil
    ApplyCoords(tex)
    if width ~= false then
        tex:SetSize(width or info[2], height or info[3])
    end
    return true
end

local function OnSetAtlas(self, atlas, useAtlasSize)
    if self.bbfRetailBusy then return end
    self.bbfRetailArt, self.bbfRetailFile, self.bbfRetailFlip = nil, nil, nil
    if not BBF.RetailTexturesOn(self.bbfRetailUnit) then return end
    local current = self:GetAtlas()
    if not current or current:lower() ~= tostring(atlas):lower() then return end
    local key = ArtKey(atlas)
    if not key then return end
    if useAtlasSize or self.bbfRetailAlwaysSize then
        BBF.SetRetailArt(self, key)
    else
        BBF.SetRetailArt(self, key, nil, false)
    end
end

local function MediaName(path)
    local name = path:match("BetterBlizzFrames[\\/]media[\\/].-([^\\/]+)$")
    return name and name:gsub("%.png$", "")
end

local function OnSetTexture(self, path)
    if self.bbfRetailBusy then return end
    local wasSheet = self.bbfRetailArt
    self.bbfRetailArt, self.bbfRetailFile, self.bbfRetailFlip, self.bbfRetailPrepatch = nil, nil, nil, nil
    if type(path) ~= "string" then return end
    local name = MediaName(path)
    if name and BBF.RetailTexturesOn(self.bbfRetailUnit) then
        local want
        local retail = path:find("foreverTextures", 1, true) and BBF.RetailArtName(name)
        if retail then
            name = retail
            want = BBF.RetailFile(name)
        elseif path:find("[\\/]retailTextures[\\/]") or path:find("[\\/]prepatchTextures[\\/]") then
            want = BBF.RetailFile(name)
        elseif blizzFiles[name] or (prepatchFiles[name] and BBF.RetailPrepatchOn()) then
            want = BBF.RetailFile(name)
        end
        if want and want ~= path then
            self.bbfRetailBusy = true
            self:SetTexture(want)
            self.bbfRetailBusy = nil
        end
        self.bbfRetailPrepatch = (want or path):find("prepatchTextures", 1, true) and true or nil
    end
    self.bbfRetailFile = name
    if wasSheet then
        self.bbfRetailBusy = true
        self:SetTexCoord(0, 1, 0, 1)
        self.bbfRetailBusy = nil
    end
end

local function OnSetTexCoord(self, a, b, c, d, e)
    if self.bbfRetailBusy or e ~= nil then return end
    if not self.bbfRetailArt and not self.bbfRetailFile then return end
    if a == 1 and b == 0 and c == 0 and d == 1 then
        self.bbfRetailFlip = true
    elseif a == 0 and b == 1 and c == 0 and d == 1 then
        self.bbfRetailFlip = nil
    else
        return
    end
    if self.bbfRetailArt then
        ApplyCoords(self)
    end
end

