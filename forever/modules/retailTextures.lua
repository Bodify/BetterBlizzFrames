        BBF.ApplyNameLayouts()
    end
end

local function HookOnce(region, method, func)
    region.bbfSymmetricHooks = region.bbfSymmetricHooks or {}
    if region.bbfSymmetricHooks[method] then return end
    region.bbfSymmetricHooks[method] = true
    hooksecurefunc(region, method, func)
end

local function Guarded(func)
    return function(self, ...)
        if self.bbfSymmetricChanging or InCombatLockdown() then return end
        self.bbfSymmetricChanging = true
        func(self, ...)
        self.bbfSymmetricChanging = false
    end
end

local function PlacePortraitMask(mask)
    mask:SetSize(56, 56)
end

local function PlaceStatus(status)
    if BBF.BigPlayerHealthbar() then
        status:SetTexture(RETAIL_TEX .. "Target-Status-BigHealthbar" .. (BBF.BigHealthbarReduced(PlayerFrame) and "-Reduced" or "") .. ".png")
        status:SetTexCoord(1, 0, 0, 1)
        status:SetSize(194, 70)
    else
        BBF.SetRetailArt(status, "Target-MinusMob-PortraitOn-Status", true, 194, 70)
    end
    status:ClearAllPoints()
    status:SetPoint("TOPLEFT", PlayerFrame.PlayerFrameContainer, "TOPLEFT", 20, -13.5)
end

function BBF.PlaceSymmetricStatus()
    if not BBF.SymmetricPlayerOn() then return end
    PlaceStatus(PlayerFrame.PlayerFrameContent.PlayerFrameContentMain.StatusTexture)
end

local function UsesAltThreat()
    return PlayerFrame.PlayerFrameContainer.AlternatePowerFrameTexture:IsShown() and not BetterBlizzFramesDB.hideUnitFramePlayerSecondResource
end

local function PlaceThreat(threat)
    local art = BBF.MirrorPlayerTargetArt()
    if art then
        threat:SetTexture(BBF.MirrorPlayerTargetArt(true))
        threat:SetTexCoord(1, 0, 0, 1)
        threat:SetSize(188, 67)
    elseif UsesAltThreat() then
        threat:SetTexture(BLIZZ_TEX .. "UI-HUD-UnitFrame-Player-PortraitOn-InCombat-Alt-Mirror.png")
        threat:SetTexCoord(0, 1, 0, 1)
        threat:SetSize(192, 67.5)
    else
        BBF.SetRetailArt(threat, "Target-PortraitOn-InCombat", true, 188, 67)
    end
    if art then
        threat:SetPoint("CENTER", 0.5, 2)
    elseif UsesAltThreat() then
        threat:SetPoint("CENTER", 0, 1.5)
    else
        threat:SetPoint("CENTER", 0.5, 1)
    end
end

function BBF.SymmetricPlayerFrame()
    if not BBF.SymmetricPlayerOn() then return end
    if InCombatLockdown() then
        BBF.RunAfterCombat(BBF.SymmetricPlayerFrame)
        return
    end
    BBF.UnregisterPlayerFrameArtEvents()

    local container = PlayerFrame.PlayerFrameContainer
    local main = PlayerFrame.PlayerFrameContent.PlayerFrameContentMain

    local portraitMask = container.PlayerPortraitMask
    portraitMask:SetAtlas("CircleMask")
    portraitMask:SetPoint("TOPLEFT", 27, -20)
    HookOnce(portraitMask, "SetSize", Guarded(PlacePortraitMask))
    PlacePortraitMask(portraitMask)

    local corner = PlayerFrame.PlayerFrameContent.PlayerFrameContentContextual.PlayerPortraitCornerIcon
    if corner then corner:SetAtlas(nil) end

    local portrait = container.PlayerPortrait
    portrait:SetSize(58.5, 58.5)
    portrait:SetPoint("TOPLEFT", 26, -18)

    local status = main.StatusTexture
    HookOnce(status, "SetAtlas", Guarded(PlaceStatus))
    HookOnce(status, "SetPoint", Guarded(PlaceStatus))
    PlaceStatus(status)

    local threat = PlayerFrame.threatIndicator or container.FrameFlash
    HookOnce(threat, "SetAtlas", Guarded(PlaceThreat))
    HookOnce(threat, "SetPoint", Guarded(PlaceThreat))
    PlaceThreat(threat)

    BBF.UpdateBigPlayerHealthbar()
end
